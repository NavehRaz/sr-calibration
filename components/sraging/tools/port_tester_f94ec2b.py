"""Generate `src/sraging/compat/tester_f94ec2b/` from the frozen tester snapshot, verbatim (spec 006, T006; research R3).

The tester's window rule, `apply_window` (srbench/library/observation.py), copied out of `tests/oracle/tester_f94ec2b`
by AST position -- never retyped -- with no edit. Library code cannot import tests/oracle, so W and H run this copy;
`VERBATIM.toml` records it for `tests/unit/test_verbatim.py` (mode "subset", the source's sha256 from the snapshot's
own manifest). Reads nothing outside this repository.

    .venv/bin/python tools/port_tester_f94ec2b.py
"""
from __future__ import annotations

import ast
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import port_v033 as P  # noqa: E402  (top_level_defs, segment, rel)

REPO = P.REPO
SNAP = os.path.join(REPO, "tests", "oracle", "tester_f94ec2b")
SRC = os.path.join(SNAP, "srbench", "library", "observation.py")
OUT = os.path.join(REPO, "src", "sraging", "compat", "tester_f94ec2b")
NAMES = ["apply_window"]
IMPORTS = "from __future__ import annotations\n\nimport numpy as np\n"


def sha256(path) -> str:
    return hashlib.sha256(open(path, "rb").read()).hexdigest()


def main():
    manifest = {f["path"]: f["sha256"] for f in json.load(open(os.path.join(SNAP, "MANIFEST.json")))["files"]}
    pinned = manifest["srbench/library/observation.py"]
    assert sha256(SRC) == pinned, "the snapshot's observation.py differs from its own manifest"
    text = open(SRC).read()
    lines = text.splitlines(keepends=True)
    defs = P.top_level_defs(ast.parse(text))
    body = "\n\n".join(P.segment(lines, defs[n])[2] for n in NAMES)
    os.makedirs(OUT, exist_ok=True)
    head = (f"# VERBATIM port of {P.rel(SRC)} (sha256 {pinned}), generated by tools/port_tester_f94ec2b.py.\n"
            "# Do not edit by hand. The tester's window rule (spec 006 R3): W and H apply it before the frozen\n"
            "# observation model.\n")
    open(os.path.join(OUT, "observation.py"), "w").write(head + IMPORTS + "\n\n" + body)
    open(os.path.join(OUT, "__init__.py"), "w").write(
        '"""The tester\'s window rule, VERBATIM from the frozen snapshot `tests/oracle/tester_f94ec2b` (spec 006,\n'
        "research R3).\n\nGenerated by `tools/port_tester_f94ec2b.py`; declared in `VERBATIM.toml` and enforced by\n"
        "`tests/unit/test_verbatim.py`. Never edit these modules by hand -- regenerate them.\n\"\"\"\n")
    open(os.path.join(OUT, "VERBATIM.toml"), "w").write(
        "# Declared provenance of every module in sraging/compat/tester_f94ec2b (no edit).\n"
        "# Written by tools/port_tester_f94ec2b.py; read by tests/unit/test_verbatim.py (spec 006 research R3).\n\n"
        "[[module]]\n"
        'port = "observation.py"\n'
        f'source = "{P.rel(SRC)}"\n'
        'mode = "subset"\n'
        f'source_sha256 = "{pinned}"\n'
        f"names = {json.dumps(NAMES)}\n")
    print(f"wrote {P.rel(OUT)}: {NAMES} from {P.rel(SRC)}")


if __name__ == "__main__":
    main()
