"""Generate `src/sraging/compat/v033/` from the frozen oracle snapshot, verbatim (tasks T009-T015).

Copies source TEXT out of `tests/oracle/v033` by AST position -- never retyped -- applies only the edits
declared below, and writes `VERBATIM.toml`, which `tests/unit/test_verbatim.py` uses to prove the port
equals the snapshot after exactly those edits (research R2). Run it again to regenerate; it never reads
or writes anything outside this repository, and never writes into the snapshot.

    .venv/bin/python tools/port_v033.py
"""
from __future__ import annotations

import ast
import hashlib
import json
import os
import textwrap

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SNAP = os.path.join(REPO, "tests", "oracle", "v033")
SRK = os.path.join(SNAP, "SRtools_kappa", "SRK")
METHOD = os.path.join(SNAP, "sr_calibration_tester", "methods", "mle_profile_jax")
OUT = os.path.join(REPO, "src", "sraging", "compat", "v033")
ALIAS_IMPORT = "from sraging.compat.v033 import fp_likelihood as _fpl"


def rel(p):
    return os.path.relpath(p, REPO)


def md5(p):
    return hashlib.md5(open(p, "rb").read()).hexdigest()


def top_level_defs(tree):
    """name -> node, for top-level functions, classes and single-name assignments."""
    out = {}
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.ClassDef)):
            out[n.name] = n
        elif isinstance(n, ast.Assign) and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name):
            out[n.targets[0].id] = n
        elif isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name):
            out[n.target.id] = n
    return out


def closure(tree, roots):
    defs = top_level_defs(tree)
    seen, stack, uses_fpl = set(), list(roots), False
    while stack:
        k = stack.pop()
        if k in seen or k not in defs:
            continue
        seen.add(k)
        for n in ast.walk(defs[k]):
            if isinstance(n, ast.Name):
                if n.id == "_fpl":
                    uses_fpl = True
                if n.id in defs and n.id not in seen:
                    stack.append(n.id)
    return [n for n in defs if n in seen], uses_fpl   # in source order


def segment(lines, node):
    """Source text of a top-level node: decorators + the contiguous comment block right above it."""
    start = min([node.lineno] + [d.lineno for d in getattr(node, "decorator_list", [])])
    while start - 2 >= 0 and lines[start - 2].lstrip().startswith("#"):
        start -= 1
    return start, node.end_lineno, "".join(lines[start - 1:node.end_lineno])


def subset_port(src, roots, imports, out_name, purpose, text_edits=(), extra_names=()):
    text = open(src).read()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    names, uses_fpl = closure(tree, list(roots) + list(extra_names))
    defs = top_level_defs(tree)
    body = []
    for name in names:
        s, e, seg = segment(lines, defs[name])
        body.append((s, seg))
    body.sort()
    code = "".join(seg + "\n\n" for _, seg in body)
    for old, new in text_edits:
        assert code.count(old) == 1, (out_name, old)
        code = code.replace(old, new)
    hdr = (f'"""VERBATIM port (sraging.compat.v033) of `{rel(src)}` -- {purpose}\n\n'
           f"Source md5 {md5(src)} (tests/oracle/v033/MANIFEST.json). Generated by tools/port_v033.py;\n"
           f"do not edit by hand. Ported names, in source order: {', '.join(names)}.\n"
           f"Allowed edits are declared in VERBATIM.toml and checked by tests/unit/test_verbatim.py.\n"
           f'"""\n')
    imps = list(imports) + ([ALIAS_IMPORT] if uses_fpl else [])
    open(os.path.join(OUT, out_name), "w").write(hdr + "\n".join(imps) + "\n\n\n" + code.rstrip() + "\n")
    return names, uses_fpl


def whole_port(src, out_name, text_edits, banner):
    text = open(src).read()
    for old, new in text_edits:
        assert text.count(old) == 1, (out_name, old)
        text = text.replace(old, new)
    head = "".join(f"# {l}\n" if l else "#\n" for l in banner.splitlines())
    open(os.path.join(OUT, out_name), "w").write(head + text)


def main():
    os.makedirs(OUT, exist_ok=True)
    edits = []   # VERBATIM.toml entries

    # ---- fp_likelihood: KM, the auto grid, the NumPy FP solver, and their helpers ----------------
    fpl_src = os.path.join(SRK, "fp_likelihood.py")
    ceil_old = ('    _ceil = _os.environ.get("SRK_DT_CEILING")\n'
                '    if _ceil:\n'
                '        dt = min(dt, float(_ceil))\n')
    ceil_new = ('    # [sraging] The SRK_DT_CEILING environment hook that stood here was REMOVED (register D-103,\n'
                '    # research R2): no environment variable may change numerics (constitution VIII). The\n'
                '    # v0.3.3 reference ran with it unset, which is exactly the behaviour kept here.\n')
    fpl_names, _ = subset_port(
        fpl_src, ["kaplan_meier", "auto_grid", "fpt_full", "_bernoulli", "_trapz", "to_dimensionless"],
        ["import numpy as np", "from scipy.linalg import solve_banded"],
        "fp_likelihood.py", "Kaplan-Meier, the automatic grid and the NumPy FP solver.",
        text_edits=[(ceil_old, ceil_new)])
    edits.append(dict(port="fp_likelihood.py", source=rel(fpl_src), mode="subset", names=fpl_names,
                      edit=[dict(kind="delete_statements", name="auto_grid",
                                 match=["_ceil = _os.environ.get('SRK_DT_CEILING')",
                                        "if _ceil:\n    dt = min(dt, float(_ceil))"],
                                 reason="SRK_DT_CEILING environment hook (D-103); unset in v0.3.3")]))

    # ---- fp_gof: the profile-interval rule (working-tree version, as snapshotted) -------------------
    gof_src = os.path.join(SRK, "fp_gof.py")
    gof_names, gof_fpl = subset_port(
        gof_src, ["profile_ci"], ["import math", "", "import numpy as np"],
        "fp_gof.py", "the profile-likelihood interval rule `profile_ci`.")
    edits.append(dict(port="fp_gof.py", source=rel(gof_src), mode="subset", names=gof_names, edit=[]))

    # ---- fp_curvefit: the curve-fit seed and its closure -----------------------------------------
    cf_src = os.path.join(SRK, "fp_curvefit.py")
    cf_names, cf_fpl = subset_port(
        cf_src, ["fp_curvefit_seed"],
        ["import math", "import time", "", "import numpy as np", "from scipy.optimize import least_squares"],
        "fp_curvefit.py", "the curve-fit seed `fp_curvefit_seed` (the estimator's start).")
    edits.append(dict(port="fp_curvefit.py", source=rel(cf_src), mode="subset", names=cf_names,
                      edit=[dict(kind="note", reason="the try/except loader of `_fpl` is replaced by "
                                 f"`{ALIAS_IMPORT}`; module-level imports are not compared")]))

    # ---- fp_jax: the JAX likelihood, whole file ------------------------------------------------------
    fj_src = os.path.join(METHOD, "fp_jax.py")
    pj_old = 'os.environ.setdefault("PJRT_NPROC", "1")\n'
    pj_new = ('from sraging.compat.v033 import runtime as _runtime   # [sraging] replaces '
              'os.environ.setdefault("PJRT_NPROC", "1"): research R3\n_runtime.configure()\n')
    whole_port(fj_src, "fp_jax.py", [(pj_old, pj_new)],
               f"VERBATIM port of {rel(fj_src)} (md5 {md5(fj_src)}), generated by tools/port_v033.py.\n"
               "Do not edit by hand. The one edit is declared in VERBATIM.toml.")
    edits.append(dict(port="fp_jax.py", source=rel(fj_src), mode="whole", names=[],
                      edit=[dict(kind="replace_statement", old="os.environ.setdefault('PJRT_NPROC', '1')",
                                 new="from sraging.compat.v033 import runtime as _runtime\n_runtime.configure()",
                                 reason="explicit runtime (R3); PJRT_NPROC overwritten, not defaulted")]))

    # ---- estimator: the v0.3.3 profile estimator, whole file -----------------------------------------
    est_src = os.path.join(METHOD, "estimator.py")
    rw = [("from SRK import fp_likelihood as FPL", "from sraging.compat.v033 import fp_likelihood as FPL"),
          ("from SRK import fp_gof as GOF", "from sraging.compat.v033 import fp_gof as GOF"),
          ("from SRK.fp_curvefit import fp_curvefit_seed",
           "from sraging.compat.v033.fp_curvefit import fp_curvefit_seed")]
    whole_port(est_src, "estimator.py", rw,
               f"VERBATIM port of {rel(est_src)} (md5 {md5(est_src)}), generated by tools/port_v033.py.\n"
               "Do not edit by hand. The edits (three import rewrites) are declared in VERBATIM.toml.")
    edits.append(dict(port="estimator.py", source=rel(est_src), mode="whole", names=[],
                      edit=[dict(kind="import_rewrite", old=o, new=n, reason="SRK -> sraging.compat.v033")
                            for o, n in rw]))

    # ---- claims: the adapter's claim mapping, as a function --------------------------------------------
    ad_src = os.path.join(METHOD, "__init__.py")
    text = open(ad_src).read()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    defs = top_level_defs(tree)
    consts = []
    for name in ("BOUNDS", "KAPPA_MAX", "LEVEL", "VERDICT_TO_SHAPE"):
        consts.append(segment(lines, defs[name])[2])
    cls = defs["MleProfileJax"]
    cal = next(n for n in cls.body if isinstance(n, ast.FunctionDef) and n.name == "calibrate")
    stmts = cal.body
    i0 = next(i for i, s in enumerate(stmts) if ast.unparse(s).startswith("theta = list(res['theta'])"))
    i1 = next(i for i, s in enumerate(stmts) if ast.unparse(s) == "diag['dt_ceiling'] = res.get('dt_ceiling')")
    a, b = stmts[i0].lineno, stmts[i1].end_lineno
    block = textwrap.dedent("".join(lines[a - 1:b]))
    claims_py = (
        f'"""Claim and diagnostics construction of `{rel(ad_src)}` (md5 {md5(ad_src)}), as a function.\n\n'
        "The constants are VERBATIM; the body of `build` is VERBATIM lines "
        f"{a}-{b} of `MleProfileJax.calibrate` (checked as\n`logic_verbatim` by tests/unit/test_verbatim.py). "
        "`Claim` returns a dict with srbench's `Claim` field defaults\n(`srbench/contract/types.py:228-234`), "
        "so `Claim(**kw)` keeps its meaning without importing srbench. The\n`code` diagnostic "
        "(`format_code_line(prov)`) is added by the caller from sraging's own provenance.\n"
        "Generated by tools/port_v033.py; do not edit by hand.\n"
        '"""\n'
        "from __future__ import annotations\n\nimport math\n\n"
        + "\n".join(consts) + "\n\n"
        "def Claim(**kw):\n"
        '    """srbench `Claim(**kw)` as a plain dict with the dataclass defaults."""\n'
        '    out = {"parameter": None, "shape": None, "lower": None, "upper": None, "point": None,\n'
        '           "level": 0.95, "n_components": 1}\n'
        "    out.update(kw)\n"
        "    return out\n\n\n"
        "def build(res):\n"
        '    """(claims, diagnostics) from `estimator.fit`\'s result, exactly as the reference adapter builds them."""\n'
        + textwrap.indent(block, "    ")
        + "    return claims, diag\n")
    open(os.path.join(OUT, "claims.py"), "w").write(claims_py)
    edits.append(dict(port="claims.py", source=rel(ad_src), mode="logic_verbatim",
                      names=["BOUNDS", "KAPPA_MAX", "LEVEL", "VERDICT_TO_SHAPE"],
                      function="build", source_function="MleProfileJax.calibrate", source_lines=[a, b],
                      edit=[dict(kind="note", reason="body of build = calibrate statements in source_lines; "
                                 "Claim(**kw) is a dict with srbench defaults; diag['code'] added by caller")]))

    # ---- VERBATIM.toml -------------------------------------------------------------------------
    def q(s):
        return json.dumps(s, ensure_ascii=False)
    out = ["# Declared provenance and allowed edits of every module in sraging/compat/v033.",
           "# Written by tools/port_v033.py; read by tests/unit/test_verbatim.py (research R2).", ""]
    for m in edits:
        out.append("[[module]]")
        for k in ("port", "source", "mode", "function", "source_function"):
            if k in m:
                out.append(f"{k} = {q(m[k])}")
        if "source_lines" in m:
            out.append(f"source_lines = [{m['source_lines'][0]}, {m['source_lines'][1]}]")
        out.append(f"source_md5 = {q(md5(os.path.join(REPO, m['source'])))}")
        out.append("names = [" + ", ".join(q(n) for n in m["names"]) + "]")
        for e in m["edit"]:
            out.append("[[module.edit]]")
            for k, v in e.items():
                out.append(f"{k} = " + ("[" + ", ".join(q(x) for x in v) + "]" if isinstance(v, list) else q(v)))
        out.append("")
    open(os.path.join(OUT, "VERBATIM.toml"), "w").write("\n".join(out))
    print("ported:", {m["port"]: len(m["names"]) for m in edits})


if __name__ == "__main__":
    main()
