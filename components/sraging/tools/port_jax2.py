"""Generate `src/sraging/compat/jax2/` from the frozen jax2 1.0.0 snapshot, verbatim (spec 003, T004; research R1).

Copies source TEXT out of `tests/oracle/jax2_3bc5775` (and, for the Makeham curve fit, out of the v033
snapshot's hash-equal SRK) by AST position -- never retyped -- applies only the edits declared below, and
writes `VERBATIM.toml`, which `tests/unit/test_verbatim.py` uses to prove each port module equals its source
after exactly those edits. The match strings of every deleted or replaced statement are computed with
`ast.unparse` from the source statements themselves. Reads nothing outside this repository.

    .venv/bin/python tools/port_jax2.py
"""
from __future__ import annotations

import ast
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import port_v033 as P  # noqa: E402  (top_level_defs, closure, segment, md5, rel)

REPO = P.REPO
SNAP2 = os.path.join(REPO, "tests", "oracle", "jax2_3bc5775", "mle_profile_jax2")
SRK = P.SRK                                         # tests/oracle/v033/SRtools_kappa/SRK (hash-equal to jax2's)
OUT = os.path.join(REPO, "src", "sraging", "compat", "jax2")
RUNTIME_IMPORT = "from sraging.compat.v033 import runtime as _runtime"
FPL_ALIAS = "from sraging.compat.v033 import fp_likelihood as _fpl"


def banner(src, what):
    return (f"VERBATIM port of {P.rel(src)} (md5 {P.md5(src)}), generated by tools/port_jax2.py.\n"
            f"Do not edit by hand. {what}")


def write_whole(src, out_name, text_edits, what):
    text = open(src).read()
    for old, new in text_edits:
        assert text.count(old) == 1, (out_name, old)
        text = text.replace(old, new)
    head = "".join(f"# {ln}\n" if ln else "#\n" for ln in banner(src, what).splitlines())
    open(os.path.join(OUT, out_name), "w").write(head + text)


def _strip_lines(lines, a, b):
    """Blank lines a..b (1-based, inclusive) of a list of source lines, in place."""
    for i in range(a - 1, b):
        lines[i] = ""


def main():
    os.makedirs(OUT, exist_ok=True)
    edits = []

    # ---- fp_jax: the jax2 FP likelihood, whole file -------------------------------------------------------
    fj = os.path.join(SNAP2, "fp_jax.py")
    pj_old = 'os.environ.setdefault("PJRT_NPROC", "1")\n'
    pj_new = (f"{RUNTIME_IMPORT}   # [sraging] replaces os.environ.setdefault(\"PJRT_NPROC\", \"1\"): research R1\n"
              "_runtime.configure()\n")
    write_whole(fj, "fp_jax.py", [(pj_old, pj_new)], "The one edit is declared in VERBATIM.toml.")
    edits.append(dict(port="fp_jax.py", source=P.rel(fj), mode="whole", names=[],
                      edit=[dict(kind="replace_statement", old="os.environ.setdefault('PJRT_NPROC', '1')",
                                 new=f"{RUNTIME_IMPORT}\n_runtime.configure()",
                                 reason="explicit runtime (R1); PJRT_NPROC overwritten, not defaulted")]))

    # ---- estimator: the jax2 profile estimator, whole file ------------------------------------------------
    est = os.path.join(SNAP2, "estimator.py")
    rw = [("from SRK.fp_curvefit import fp_curvefit_makeham",
           "from sraging.compat.jax2.fp_curvefit_h import fp_curvefit_makeham"),
          ("from SRK import fp_likelihood as FPL", "from sraging.compat.v033 import fp_likelihood as FPL"),
          ("from SRK import fp_gof as GOF", "from sraging.compat.v033 import fp_gof as GOF"),
          ("from SRK.fp_curvefit import fp_curvefit_seed",
           "from sraging.compat.v033.fp_curvefit import fp_curvefit_seed")]
    strict_old = '    return os.environ.get("SRB_STRICT", "") not in ("", "0")\n'
    strict_new = ('    return True   # [sraging] Phase C runs with SRB_STRICT=1 (phaseC/cluster/env.sh:23); '
                  'no environment variable is read (R1)\n')
    write_whole(est, "estimator.py", rw + [(strict_old, strict_new)],
                "The edits (four import rewrites and the fixed exception policy) are declared in VERBATIM.toml.")
    edits.append(dict(port="estimator.py", source=P.rel(est), mode="whole", names=[],
                      edit=[dict(kind="import_rewrite", old=o, new=n,
                                 reason="SRK -> sraging.compat (hash-equal sources, tests/oracle/v033)")
                            for o, n in rw]
                      + [dict(kind="replace_statement", old="return os.environ.get('SRB_STRICT', '') not in ('', '0')",
                              new="return True",
                              reason="SRB_STRICT=1 is Phase C's setting (phaseC/driver_C.py:113 refuses otherwise); "
                                     "no environment variable may change behaviour (constitution VIII)")]))

    # ---- observation_model: stdlib only, whole file, no edit ----------------------------------------------
    om = os.path.join(SNAP2, "observation_model.py")
    write_whole(om, "observation_model.py", [], "No edits.")
    edits.append(dict(port="observation_model.py", source=P.rel(om), mode="whole", names=[], edit=[]))

    # ---- fp_curvefit_h: the closure of SRK's Makeham curve fit (the _h start) -----------------------------
    cf = os.path.join(SRK, "fp_curvefit.py")
    text = open(cf).read()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    names, uses_fpl = P.closure(tree, ["fp_curvefit_makeham"])
    defs = P.top_level_defs(tree)
    body = sorted((P.segment(lines, defs[n])[0], P.segment(lines, defs[n])[2]) for n in names)
    hdr = (f'"""VERBATIM port (sraging.compat.jax2) of `{P.rel(cf)}` -- the closure of `fp_curvefit_makeham`,\n'
           "the external-hazard curve fit that profile_jax2_h uses as a start (jax2 estimator.py:1038).\n\n"
           f"Source md5 {P.md5(cf)} (tests/oracle/v033/MANIFEST.json; sha256-equal to the SRK jax2 1.0.0 loads).\n"
           "Generated by tools/port_jax2.py; do not edit by hand. Ported names, in source order: "
           f"{', '.join(names)}.\n"
           '"""\n')
    imps = ["import math", "import time", "", "import numpy as np", "from scipy.optimize import least_squares"]
    if uses_fpl:
        imps.append(FPL_ALIAS)
    open(os.path.join(OUT, "fp_curvefit_h.py"), "w").write(
        hdr + "\n".join(imps) + "\n\n\n" + "".join(seg + "\n\n" for _, seg in body).rstrip() + "\n")
    edits.append(dict(port="fp_curvefit_h.py", source=P.rel(cf), mode="subset", names=names,
                      edit=[dict(kind="note", reason=f"the try/except loader of `_fpl` is replaced by `{FPL_ALIAS}`; "
                                 "module-level imports are not compared")]))

    # ---- claims: the package's fit path and claim builders (__init__.py), as a subset ---------------------
    ini = os.path.join(SNAP2, "__init__.py")
    text = open(ini).read()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    defs = P.top_level_defs(tree)
    keep = ["VERSIONS", "BOUNDS", "KAPPA_MAX", "LEVEL", "VERDICT_TO_SHAPE", "SC_EDGE_DEX", "run_fit",
            "h_claim_kwargs", "claim_kwargs", "sc_widen_claim", "sc_widen_claims", "final_claim_kwargs"]
    rf = defs["run_fit"]
    rf_lines = lines[:]                                         # edited copy, for run_fit's text only
    deletes, replaces = [], []
    sib = {"observation_model": "om", "fp_jax": "fj", "estimator": "est"}
    for st in rf.body:
        u = ast.unparse(st)
        if (u in ("env_guard()", "version_lock_guard()", "from srbench import npcompat",
                  "srk0 = srk_fingerprint()", "srk1 = srk_fingerprint()", "dg['srk_sha'] = srk")
                or u.startswith("for m in _SRK_MODULES:") or u.startswith("files = dict(srk1['files']")
                or u.startswith("changed = sorted(") or u.startswith("srk = dict(root=srk0['root']")):
            deletes.append(u)
            _strip_lines(rf_lines, st.lineno, st.end_lineno)
        elif isinstance(st, ast.Assign) and u.startswith(tuple(f"{v} = _sibling(" for v in sib.values())):
            var = st.targets[0].id
            mod = next(k for k, v in sib.items() if v == var)
            new = f"from sraging.compat.jax2 import {mod} as {var}"
            replaces.append((u, new))
            ind = lines[st.lineno - 1][: len(lines[st.lineno - 1]) - len(lines[st.lineno - 1].lstrip())]
            _strip_lines(rf_lines, st.lineno, st.end_lineno)
            rf_lines[st.lineno - 1] = f"{ind}{new}   # [sraging] replaces {u} (R1)\n"
    assert len(set(deletes)) == 10 and len(replaces) == 3, (sorted(set(deletes)), replaces)
    segs = []
    for name in keep:
        s, e, seg = P.segment(lines, defs[name])
        if name == "run_fit":
            seg = "".join(ln for ln in rf_lines[s - 1:e] if ln != "")
        segs.append((s, seg))
    segs.sort()
    claims_hdr = (
        f'"""The jax2 1.0.0 package\'s fit path and claim builders: VERBATIM from `{P.rel(ini)}` (md5 {P.md5(ini)}).\n\n'
        "Ported names (each compared with its source by tests/unit/test_verbatim.py after the declared edits):\n"
        f"{', '.join(keep)}. In `run_fit` the tester's deployment guards are deleted -- env_guard (estimator.fit\n"
        "refuses SRK_DT_CEILING itself, estimator.py:1533), version_lock_guard, the srbench npcompat import, the SRK\n"
        "pre-import and the srk_sha fingerprint (tester provenance with a host path; sraging records its own) -- and\n"
        "the three sibling loads become compat imports. `Observation` is an unevaluated annotation (from __future__\n"
        "import annotations): any object with ages, events, delta and window serves. Generated by\n"
        "tools/port_jax2.py; do not edit by hand.\n"
        '"""\n'
        "from __future__ import annotations\n\nimport math\nimport os\n\n\n")
    open(os.path.join(OUT, "claims.py"), "w").write(claims_hdr + "".join(seg + "\n\n" for _, seg in segs).rstrip() + "\n")
    edits.append(dict(port="claims.py", source=P.rel(ini), mode="subset", names=keep,
                      edit=[dict(kind="delete_statements", name="run_fit", match=sorted(set(deletes)),
                                 reason="the tester's deployment guards and srk_sha fingerprint (R1)")]
                      + [dict(kind="replace_statement", name="run_fit", old=o, new=n,
                              reason="sibling load -> compat import (R1)") for o, n in replaces]))

    # ---- settings: the registered names' class constants (what `calibrate` passes to run_fit) -------------
    classes = ["_MleProfileJax2Base", "MleProfileJax2", "MleProfileJax2H"]
    consts = ["NAME", "HAZARD", "WINDOW", "RELABEL", "SELF_CONSISTENT", "N_RULE", "DT_RULE", "FLOOR_EARLY",
              "EARLY_ALL", "SHADOW", "EXACT_F"]
    body = ['"""The registered names\' class constants, VERBATIM from `%s` (md5 %s).\n\n' % (P.rel(ini), P.md5(ini))
            + "Only the constant assignments of the three classes are kept (the classes' methods are the tester's\n"
              "srbench integration: `calibrate` passes exactly these to `run_fit`, __init__.py:678-681). Inheritance is\n"
              "kept, so a subclass's override wins as in the source. Checked as `class_constants` by\n"
              "tests/unit/test_verbatim.py. Generated by tools/port_jax2.py; do not edit by hand.\n"
            + '"""\n\n']
    for cname in classes:
        node = defs[cname]
        body.append(lines[node.lineno - 1])
        n_kept = 0
        for st in node.body:
            if isinstance(st, ast.Assign) and len(st.targets) == 1 and isinstance(st.targets[0], ast.Name) \
                    and st.targets[0].id in consts:
                body.append("".join(lines[st.lineno - 1:st.end_lineno]))
                n_kept += 1
        assert n_kept, cname
        body.append("\n\n")
    open(os.path.join(OUT, "settings.py"), "w").write("".join(body).rstrip() + "\n")
    edits.append(dict(port="settings.py", source=P.rel(ini), mode="class_constants", names=classes,
                      constants=consts, edit=[]))

    # ---- VERBATIM.toml --------------------------------------------------------------------------------
    def q(s):
        return json.dumps(s, ensure_ascii=False)
    out = ["# Declared provenance and allowed edits of every module in sraging/compat/jax2.",
           "# Written by tools/port_jax2.py; read by tests/unit/test_verbatim.py (spec 003 research R1).", ""]
    for m in edits:
        out.append("[[module]]")
        for k in ("port", "source", "mode"):
            out.append(f"{k} = {q(m[k])}")
        if "constants" in m:
            out.append("constants = [" + ", ".join(q(n) for n in m["constants"]) + "]")
        out.append(f"source_md5 = {q(P.md5(os.path.join(REPO, m['source'])))}")
        out.append("names = [" + ", ".join(q(n) for n in m["names"]) + "]")
        for e in m["edit"]:
            out.append("[[module.edit]]")
            for k, v in e.items():
                out.append(f"{k} = " + ("[" + ", ".join(q(x) for x in v) + "]" if isinstance(v, list) else q(v)))
        out.append("")
    open(os.path.join(OUT, "VERBATIM.toml"), "w").write("\n".join(out))
    open(os.path.join(OUT, "__init__.py"), "w").write(
        '"""The jax2 1.0.0 numerics, VERBATIM from the frozen oracle `tests/oracle/jax2_3bc5775` (spec 003, research R1).\n\n'
        "Legacy code: positional z = log(theta) vectors live only here. Generated by `tools/port_jax2.py`; the\n"
        "allowed edits are declared in `VERBATIM.toml` and enforced by `tests/unit/test_verbatim.py`. Never edit\n"
        "these modules by hand -- regenerate them. Importing this package configures the JAX runtime (v033's).\n"
        '"""\n'
        f"{RUNTIME_IMPORT}\n\n_runtime.configure()\n")
    print("ported:", {m["port"]: len(m["names"]) for m in edits})


if __name__ == "__main__":
    main()
