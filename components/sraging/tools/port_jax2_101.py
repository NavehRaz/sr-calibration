"""Generate `src/sraging/compat/jax2_101/` from the frozen jax2 1.0.1 snapshot, verbatim (spec 003b, T007; research R1).

The same method as `tools/port_jax2.py` (which generated `compat/jax2/` from the 1.0.0 snapshot, and is not changed):
source TEXT is copied out of `tests/oracle/jax2_6884fc8` (and, for the Makeham curve fit, out of the v033 snapshot's
hash-equal SRK) by AST position -- never retyped -- only the declared edits are applied, and `VERBATIM.toml` records
them for `tests/unit/test_verbatim.py`. The match strings of every deleted or replaced statement are computed with
`ast.unparse` from the source statements themselves, and asserted, not reused from 1.0.0. Reads nothing outside this
repository.

    .venv/bin/python tools/port_jax2_101.py
"""
from __future__ import annotations

import ast
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import port_v033 as P  # noqa: E402  (top_level_defs, closure, segment, md5, rel)

REPO = P.REPO
SNAP = os.path.join(REPO, "tests", "oracle", "jax2_6884fc8", "mle_profile_jax2")
SRK = P.SRK
PKG = "jax2_101"
OUT = os.path.join(REPO, "src", "sraging", "compat", PKG)
RUNTIME_IMPORT = "from sraging.compat.v033 import runtime as _runtime"
FPL_ALIAS = "from sraging.compat.v033 import fp_likelihood as _fpl"
VERSION = "1.0.1"

# research R1: 1.0.0's keep-list, plus the estimate block (spec 002 at the freeze) and the kappa-fixed builders
KEEP = ["VERSIONS", "BOUNDS", "KAPPA_MAX", "LEVEL", "VERDICT_TO_SHAPE", "SC_EDGE_DEX", "KFIX_KAPPAS", "kappa_tag",
        "kfix_name", "rbar", "COMBO_BOX", "ESTIMATE_KEY", "ESTIMATE_SCHEMA", "run_fit", "h_claim_kwargs", "claim_kwargs",
        "sc_widen_claim", "sc_widen_claims", "final_claim_kwargs", "combo_claim_kwargs", "kfix_claim_kwargs",
        "box_limited_block", "estimate_block"]
CLASSES = ["_MleProfileJax2Base", "MleProfileJax2", "MleProfileJax2H", "MleProfileJax2KfixK0p001",
           "MleProfileJax2KfixK0p5", "MleProfileJax2KfixK1", "MleProfileJax2HKfixK0p001", "MleProfileJax2HKfixK0p5",
           "MleProfileJax2HKfixK1"]
CONSTS = ["NAME", "HAZARD", "WINDOW", "RELABEL", "SELF_CONSISTENT", "N_RULE", "DT_RULE", "FLOOR_EARLY", "EARLY_ALL",
          "SHADOW", "EXACT_F", "INNER_POLISH_J", "BRACKET_BISECT", "EXTENT_Z", "BOX_FLAG", "KAPPA0", "COMBOS",
          "KEEP_PROFILES"]
RUN_FIT_DELETES = ("env_guard()", "version_lock_guard()", "from srbench import npcompat", "srk0 = srk_fingerprint()",
                   "srk1 = srk_fingerprint()", "dg['srk_sha'] = srk")
RUN_FIT_DELETE_PREFIXES = ("for m in _SRK_MODULES:", "files = dict(srk1['files']", "changed = sorted(",
                           "srk = dict(root=srk0['root']")


def banner(src, what):
    return (f"VERBATIM port of {P.rel(src)} (md5 {P.md5(src)}), generated by tools/port_jax2_101.py.\n"
            f"Do not edit by hand. {what}")


def write_whole(src, out_name, text_edits, what):
    text = open(src).read()
    for old, new in text_edits:
        assert text.count(old) == 1, (out_name, old)
        text = text.replace(old, new)
    head = "".join(f"# {ln}\n" if ln else "#\n" for ln in banner(src, what).splitlines())
    open(os.path.join(OUT, out_name), "w").write(head + text)


def _strip_lines(lines, a, b):
    for i in range(a - 1, b):
        lines[i] = ""


def _module_imports(tree):
    """{bound name: import statement text} for the module-level imports of a source module."""
    out = {}
    for n in tree.body:
        if isinstance(n, ast.Import):
            for a in n.names:
                out[a.asname or a.name.split(".")[0]] = f"import {a.name}" + (f" as {a.asname}" if a.asname else "")
        elif isinstance(n, ast.ImportFrom) and n.module != "__future__":
            for a in n.names:
                out[a.asname or a.name] = f"from {n.module} import {a.name}" + (f" as {a.asname}" if a.asname else "")
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    edits = []

    # ---- fp_jax: whole file, the one runtime edit (its source is byte-identical to 1.0.0's) ---------------------
    fj = os.path.join(SNAP, "fp_jax.py")
    pj_old = 'os.environ.setdefault("PJRT_NPROC", "1")\n'
    pj_new = (f"{RUNTIME_IMPORT}   # [sraging] replaces os.environ.setdefault(\"PJRT_NPROC\", \"1\"): research R1\n"
              "_runtime.configure()\n")
    write_whole(fj, "fp_jax.py", [(pj_old, pj_new)], "The one edit is declared in VERBATIM.toml.")
    edits.append(dict(port="fp_jax.py", source=P.rel(fj), mode="whole", names=[],
                      edit=[dict(kind="replace_statement", old="os.environ.setdefault('PJRT_NPROC', '1')",
                                 new=f"{RUNTIME_IMPORT}\n_runtime.configure()",
                                 reason="explicit runtime (R1); PJRT_NPROC overwritten, not defaulted")]))

    # ---- estimator: whole file (dev5's bytes), the four import rewrites and the fixed exception policy ----------
    est = os.path.join(SNAP, "estimator.py")
    rw = [("from SRK.fp_curvefit import fp_curvefit_makeham",
           f"from sraging.compat.{PKG}.fp_curvefit_h import fp_curvefit_makeham"),
          ("from SRK import fp_likelihood as FPL", "from sraging.compat.v033 import fp_likelihood as FPL"),
          ("from SRK import fp_gof as GOF", "from sraging.compat.v033 import fp_gof as GOF"),
          ("from SRK.fp_curvefit import fp_curvefit_seed",
           "from sraging.compat.v033.fp_curvefit import fp_curvefit_seed")]
    strict_old = '    return os.environ.get("SRB_STRICT", "") not in ("", "0")\n'
    strict_new = ('    return True   # [sraging] Phase C runs with SRB_STRICT=1 (phaseC/cluster/env.sh:23); '
                  'no environment variable is read (R1)\n')
    write_whole(est, "estimator.py", rw + [(strict_old, strict_new)],
                "The edits (four import rewrites and the fixed exception policy) are declared in VERBATIM.toml.")
    edits.append(dict(port="estimator.py", source=P.rel(est), mode="whole", names=[],
                      edit=[dict(kind="import_rewrite", old=o, new=n,
                                 reason="SRK -> sraging.compat (hash-equal sources, tests/oracle/v033)")
                            for o, n in rw]
                      + [dict(kind="replace_statement", old="return os.environ.get('SRB_STRICT', '') not in ('', '0')",
                              new="return True",
                              reason="SRB_STRICT=1 is the validation runs' setting (handoff section 5); no environment "
                                     "variable may change behaviour (constitution VIII)")]))

    # ---- observation_model: whole file, no edit (byte-identical to 1.0.0's) -----------------------------------
    om = os.path.join(SNAP, "observation_model.py")
    write_whole(om, "observation_model.py", [], "No edits.")
    edits.append(dict(port="observation_model.py", source=P.rel(om), mode="whole", names=[], edit=[]))

    # ---- fp_curvefit_h: the closure of SRK's Makeham curve fit (the _h start), as for 1.0.0 -------------------
    cf = os.path.join(SRK, "fp_curvefit.py")
    text = open(cf).read()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    names, uses_fpl = P.closure(tree, ["fp_curvefit_makeham"])
    defs = P.top_level_defs(tree)
    body = sorted((P.segment(lines, defs[n])[0], P.segment(lines, defs[n])[2]) for n in names)
    hdr = (f'"""VERBATIM port (sraging.compat.{PKG}) of `{P.rel(cf)}` -- the closure of `fp_curvefit_makeham`,\n'
           "the external-hazard curve fit that profile_jax2_h uses as a start (jax2 1.0.1 estimator.py:1722).\n\n"
           f"Source md5 {P.md5(cf)} (tests/oracle/v033/MANIFEST.json; sha256-equal to the SRK jax2 1.0.1 loads).\n"
           "Generated by tools/port_jax2_101.py; do not edit by hand. Ported names, in source order: "
           f"{', '.join(names)}.\n"
           '"""\n')
    imps = ["import math", "import time", "", "import numpy as np", "from scipy.optimize import least_squares"]
    if uses_fpl:
        imps.append(FPL_ALIAS)
    open(os.path.join(OUT, "fp_curvefit_h.py"), "w").write(
        hdr + "\n".join(imps) + "\n\n\n" + "".join(seg + "\n\n" for _, seg in body).rstrip() + "\n")
    edits.append(dict(port="fp_curvefit_h.py", source=P.rel(cf), mode="subset", names=names,
                      edit=[dict(kind="note", reason=f"the try/except loader of `_fpl` is replaced by `{FPL_ALIAS}`; "
                                 "module-level imports are not compared")]))

    # ---- claims: the package's fit path, claim builders, estimate block and kappa-fixed builders (subset) ------
    ini = os.path.join(SNAP, "__init__.py")
    text = open(ini).read()
    lines = text.splitlines(keepends=True)
    tree = ast.parse(text)
    defs = P.top_level_defs(tree)
    missing = [n for n in KEEP if n not in defs]
    assert not missing, missing
    rf = defs["run_fit"]
    rf_lines = lines[:]
    deletes, replaces = [], []
    sib = {"observation_model": "om", "fp_jax": "fj", "estimator": "est"}
    for st in rf.body:
        u = ast.unparse(st)
        if u in RUN_FIT_DELETES or u.startswith(RUN_FIT_DELETE_PREFIXES):
            deletes.append(u)
            _strip_lines(rf_lines, st.lineno, st.end_lineno)
        elif isinstance(st, ast.Assign) and u.startswith(tuple(f"{v} = _sibling(" for v in sib.values())):
            var = st.targets[0].id
            mod = next(k for k, v in sib.items() if v == var)
            new = f"from sraging.compat.{PKG} import {mod} as {var}"
            replaces.append((u, new))
            ind = lines[st.lineno - 1][: len(lines[st.lineno - 1]) - len(lines[st.lineno - 1].lstrip())]
            _strip_lines(rf_lines, st.lineno, st.end_lineno)
            rf_lines[st.lineno - 1] = f"{ind}{new}   # [sraging] replaces {u} (R1)\n"
    # every deployment guard of 1.0.0's list is present in 1.0.1's run_fit (version_lock_guard() appears twice)
    assert set(deletes) >= set(RUN_FIT_DELETES) and len(set(deletes)) == 10 and len(replaces) == 3, \
        (sorted(set(deletes)), replaces)
    segs = []
    for name in KEEP:
        s, e, seg = P.segment(lines, defs[name])
        if name == "run_fit":
            seg = "".join(ln for ln in rf_lines[s - 1:e] if ln != "")
        segs.append((s, seg))
    segs.sort()
    used = set()
    for _s, seg in segs:
        used |= {n.id for n in ast.walk(ast.parse(seg)) if isinstance(n, ast.Name)}
    avail = _module_imports(tree)
    keep_names = set(KEEP)
    imports = sorted({avail[n] for n in used if n in avail and n not in keep_names
                      and not avail[n].startswith(("from srbench", "import SRK"))})
    claims_hdr = (
        f'"""The jax2 1.0.1 package\'s fit path, claim builders, estimate block and kappa-fixed builders: VERBATIM from\n'
        f'`{P.rel(ini)}` (md5 {P.md5(ini)}).\n\n'
        "Ported names (each compared with its source by tests/unit/test_verbatim.py after the declared edits):\n"
        f"{', '.join(KEEP)}. In `run_fit` the tester's deployment guards are deleted, as in the 1.0.0 port -- env_guard,\n"
        "version_lock_guard, the srbench npcompat import, the SRK pre-import and the srk_sha fingerprint -- and the three\n"
        "sibling loads become compat imports. Module-level imports are the source's, for the names the kept code uses.\n"
        "Generated by tools/port_jax2_101.py; do not edit by hand.\n"
        '"""\n'
        "from __future__ import annotations\n\n" + "\n".join(imports) + "\n\n\n")
    open(os.path.join(OUT, "claims.py"), "w").write(claims_hdr + "".join(seg + "\n\n" for _, seg in segs).rstrip() + "\n")
    edits.append(dict(port="claims.py", source=P.rel(ini), mode="subset", names=KEEP,
                      edit=[dict(kind="delete_statements", name="run_fit", match=sorted(set(deletes)),
                                 reason="the tester's deployment guards and srk_sha fingerprint (R1)")]
                      + [dict(kind="replace_statement", name="run_fit", old=o, new=n,
                              reason="sibling load -> compat import (R1)") for o, n in replaces]))

    # ---- settings: the 8 names' class constants (what `calibrate` passes to run_fit), 6 kappa-fixed unregistered --
    body = ['"""The 1.0.1 names\' class constants, VERBATIM from `%s` (md5 %s).\n\n' % (P.rel(ini), P.md5(ini))
            + "Only the constant assignments of the nine classes are kept (the classes' methods are the tester's\n"
              "srbench integration: `calibrate` passes exactly these to `run_fit`). The six kappa-fixed classes are\n"
              "ported but never registered by sraging (spec 003b FR-007). Checked as `class_constants` by\n"
              "tests/unit/test_verbatim.py. Generated by tools/port_jax2_101.py; do not edit by hand.\n"
            + '"""\n\n']
    for cname in CLASSES:
        node = defs[cname]
        body.append(lines[node.lineno - 1])
        n_kept = 0
        for st in node.body:
            if isinstance(st, ast.Assign) and len(st.targets) == 1 and isinstance(st.targets[0], ast.Name) \
                    and st.targets[0].id in CONSTS:
                body.append("".join(lines[st.lineno - 1:st.end_lineno]))
                n_kept += 1
        assert n_kept, cname
        body.append("\n\n")
    open(os.path.join(OUT, "settings.py"), "w").write("".join(body).rstrip() + "\n")
    edits.append(dict(port="settings.py", source=P.rel(ini), mode="class_constants", names=CLASSES,
                      constants=CONSTS, edit=[]))

    # ---- VERBATIM.toml and the package ---------------------------------------------------------------------
    def q(s):
        return json.dumps(s, ensure_ascii=False)
    out = [f"# Declared provenance and allowed edits of every module in sraging/compat/{PKG}.",
           "# Written by tools/port_jax2_101.py; read by tests/unit/test_verbatim.py (spec 003b research R1).", ""]
    for m in edits:
        out.append("[[module]]")
        for k in ("port", "source", "mode"):
            out.append(f"{k} = {q(m[k])}")
        if "constants" in m:
            out.append("constants = [" + ", ".join(q(n) for n in m["constants"]) + "]")
        out.append(f"source_md5 = {q(P.md5(os.path.join(REPO, m['source'])))}")
        out.append("names = [" + ", ".join(q(n) for n in m["names"]) + "]")
        for e in m["edit"]:
            out.append("[[module.edit]]")
            for k, v in e.items():
                out.append(f"{k} = " + ("[" + ", ".join(q(x) for x in v) + "]" if isinstance(v, list) else q(v)))
        out.append("")
    open(os.path.join(OUT, "VERBATIM.toml"), "w").write("\n".join(out))
    open(os.path.join(OUT, "__init__.py"), "w").write(
        f'"""The jax2 {VERSION} numerics, VERBATIM from the frozen oracle `tests/oracle/jax2_6884fc8` (spec 003b, research R1).\n\n'
        "Legacy code: positional z = log(theta) vectors live only here. Generated by `tools/port_jax2_101.py`; the\n"
        "allowed edits are declared in `VERBATIM.toml` and enforced by `tests/unit/test_verbatim.py`. Never edit\n"
        "these modules by hand -- regenerate them. Importing this package configures the JAX runtime (v033's).\n"
        "The 1.0.0 port, `sraging.compat.jax2`, is frozen beside it.\n"
        '"""\n'
        f"{RUNTIME_IMPORT}\n\n_runtime.configure()\n")
    print("ported:", {m["port"]: len(m["names"]) for m in edits}, "claims imports:", imports)


if __name__ == "__main__":
    main()
