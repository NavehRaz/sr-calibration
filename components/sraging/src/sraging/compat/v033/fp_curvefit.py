# defaults -- 4-param seed
# ----------------------------------------------------------------------------
XC_NOMINAL = 1.0            # threshold; NOT identifiable from the curve (use config)


KAPPA_FLOOR = 1e-3          # below this kappa the removal is effectively constant (reduced limit)


KAPPA_CEIL = 5.0            # k of order Xc; saturation matters when kappa <~ 1


N_FIT = 900                 # FP space nodes during the fit (shape-accurate, fast: ~40-70 ms/eval)


DT_FIT = 2e-3               # FP tau-step during the fit


N_POLISH = 1500             # finer grid for the final reported moments


DT_POLISH = 1e-3


TAU_MAX = 16.0              # integrate well past the absorbed tail


NGRID = 60                  # number of residual points along the survival curve


DEFAULT_EXTERNAL_HAZARD = 1e-4


# starts on each arm: (rho_eta, rho_beta, rho_eps, kappa). The fit refines from here; they only
# need to sit in the right basin. The production start has net drift > 0 (rho_eta dominates,
# removal near zero and kappa near the floor -- removal is "saturated out"); the removal start has
# net drift < 0 (rho_beta dominates) with a moderate kappa so the saturating term is active and the
# CV is nonzero from the outset (the reduced kappa->0 limit would start it at CV~0, wrong basin).
_START_PRODUCTION = (3.5, 0.2, 0.10, KAPPA_FLOOR)


_START_REMOVAL = (1.0, 6.0, 0.50, 0.30)


# ----------------------------------------------------------------------------
# forward model wrapper
# ----------------------------------------------------------------------------
def fpt_full_survival(rho_eta, rho_beta, rho_eps, kappa, tau_eval, **kw):
    """Survival G(tau) of the full saturating-removal model on a requested tau-grid.

    Convenience wrapper around fpt_full(return_survival=True): solves once, then linearly
    interpolates the survival onto `tau_eval` (clamped to 1.0 at tau=0 and to the last solved
    value, ~0, beyond the absorbing tail). Returns (G_on_tau_eval, mean, cv, S_end).

    Pass solver controls (N, dt, tau_max, Gtol) through **kw. tau_max defaults high enough that the
    curve is fully absorbed; if a requested tau exceeds the integrated range the survival is held
    at its last (near-zero) value, which is the correct asymptote.
    """
    tau_eval = np.asarray(tau_eval, dtype=float)
    mean, cv, s_end, tg, Sg = fpt_full(rho_eta, rho_beta, rho_eps, kappa,
                                       return_survival=True, **kw)
    # left-clamp to S(0)=1, right-clamp to the last solved survival (the absorbed tail ~0)
    G = np.interp(tau_eval, tg, Sg, left=1.0, right=Sg[-1])
    return G, mean, cv, s_end


# ----------------------------------------------------------------------------
# coordinate convention  (EXACT inverse of to_dimensionless)
# ----------------------------------------------------------------------------
def from_dimensionless(rho_beta, rho_eta, rho_eps, xc, L, kappa=None):
    """(rho_beta, rho_eta, rho_eps, Xc, L[, kappa]) -> physical (eta, beta, epsilon[, k])."""
    beta = rho_beta * xc / L
    eta = rho_eta * xc / L ** 2
    epsilon = rho_eps * xc ** 2 / L
    if kappa is None:
        return eta, beta, epsilon
    return eta, beta, epsilon, kappa * xc


# ----------------------------------------------------------------------------
# empirical survival on a tau grid
# ----------------------------------------------------------------------------
def _empirical_on_taugrid(tk, Sk, L, ngrid=NGRID, s_floor=2e-3):
    """Resample the KM curve onto a tau=t/L grid spanning where the curve actually moves.

    Points are placed UNIFORMLY IN SURVIVAL between 1 and s_floor (then mapped to the
    corresponding tau), so the residual weights the informative body of the curve and not the long
    dead tail. Returns (tau_grid, S_emp_on_grid, tau_hi).
    """
    tau = tk / L
    Sk = np.clip(Sk, 0.0, 1.0)
    # tau at which survival first drops to s_floor (end of the informative region)
    below = np.where(Sk <= s_floor)[0]
    tau_hi = tau[below[0]] if below.size else tau[-1]
    tau_hi = max(tau_hi, 0.2)
    # uniform-in-survival target levels -> their tau via inverse interpolation
    levels = np.linspace(1.0 - 1e-6, s_floor, ngrid)
    # Sk is non-increasing; interpolate tau as a function of (1 - S) which is increasing
    x = 1.0 - Sk
    tau_grid = np.interp(1.0 - levels, x, tau)
    # ensure strictly increasing, clip into (0, tau_hi]
    tau_grid = np.clip(np.unique(tau_grid), 1e-3, tau_hi)
    S_emp = np.interp(tau_grid, tau, Sk, left=1.0, right=Sk[-1])
    return tau_grid, S_emp, tau_hi


S_FLOOR = 0.02           # clip S before -log so the tail term stays bounded (H <= ~3.9)


RHO_CEIL = 300.0         # tightened from 2e3: the loose bound is what lets the ridge run away


_MOMENT_TAU_MAX = 40.0   # horizon for the CV/mean rows: must cover the whole absorbed tail


def _empirical_cv(tk, Sk):
    """KM-area CV of the observed lifetimes: sqrt(2*int(tau*S) - (int S)^2) / int S, in tau units.

    Closes the moment integrals on a censored tail by appending one synthetic (1.3*tau_max, S=0)
    point -- otherwise a curve still at S>0.02 at its last observation truncates both integrals and
    the CV comes out biased low.
    """
    tau = np.asarray(tk, float) / max(_trapz_area(tk, Sk), 1e-12)
    S = np.clip(np.asarray(Sk, float), 0.0, 1.0)
    if S[-1] > 0.02:
        tau = np.append(tau, tau[-1] * 1.3); S = np.append(S, 0.0)
    m1 = _trapz_area(tau, S)
    m2 = 2.0 * _trapz_area(tau, tau * S)
    if not (m1 > 0):
        return float("nan")
    return math.sqrt(max(m2 - m1 * m1, 1e-12)) / m1


def _trapz_area(x, y):
    x = np.asarray(x, float); y = np.asarray(y, float)
    return float(np.sum(np.diff(x) * (y[1:] + y[:-1]) / 2.0))


#           omega   rho_beta      arm
_SURFACE_STARTS = ((50.0,  0.10),   # production, HIGH omega
                   (2.0,   0.20),   # production, low omega
                   (-2.0,  6.00),   # removal, low |omega|
                   (-8.0, 20.00))   # removal, high |omega|


def _surface_starts(S_emp, tau_grid):
    """Extra starts read off the analytic kappa=0 surface: rho_eps = s(w)/w, rho_eta = 2(s(w)+rho_beta).

    Cheap (no PDE solve) and it covers the arm gap: omega < 0 requires rho_eps > 1/2 and omega > 0
    requires rho_eps < 1/2, so sampling both sides of 1/2 seeds both arms by construction.

    MUST STAY ARM-BALANCED, and must reach HIGH POSITIVE omega. The first version used
    omega = (+2, -2, -8): two of three starts on the removal arm, and the most positive only +2.
    Together with the two canonical starts that made 3 of 5 removal-biased, and the measured
    consequence was systematic arm flipping of production-arm cohorts -- weak-removal (rho_beta < 1)
    arm accuracy fell 0.776 -> 0.490 on the benchmark, with cases like a true omega of +48.7 that the
    survival-only fit had recovered as +53.7 being dragged to -16.0. Weak removal is exactly where
    omega is positive (omega = (0.5*rho_eta - rho_beta)/rho_eps, so small rho_beta => positive), so a
    removal-biased start set damages precisely the regime it should help.

    The surface itself is only a 7-32% approximation of the mean (worsening with rho_beta), so it is
    useless as a constraint -- but that accuracy is ample for a STARTING POINT.
    """
    out = []
    for i, (w, rb) in enumerate(_SURFACE_STARTS):
        s_w = _s_of_omega(w)
        rho_eps = s_w / w
        rho_eta = 2.0 * (s_w + rb)
        if rho_eps <= 0 or rho_eta <= 0:
            continue
        out.append((f"surface{i}", (rho_eta, rb, rho_eps, 0.15)))
    return out


def _s_of_omega(omega):
    """s(w) = 1 - (1-e^-w)/w, the averaged-drift 'sharpness'. == 0.5*rho_eta - rho_beta."""
    if abs(omega) < 1e-3:
        return omega / 2.0
    if omega < -700.0:
        return -math.exp(700.0) / 700.0
    return 1.0 - (1.0 - math.exp(-omega)) / omega


def _resid_fn(tau_grid, S_emp, use_full, N, dt, tau_max,
              chf_weight=0.0, cv_weight=0.0, mean_weight=0.0, emp_cv=None,
              s_floor=S_FLOOR):
    """Residual for z = log[rho_eta, rho_beta, rho_eps, kappa].

    With all weights 0 (the default) this is exactly the historical survival residual
    G(tau; z) - S_emp. Otherwise the vector is

        [ G - S_emp,  w_H*(H_model - H_emp),  w_C*(CV_model - CV_emp),  w_M*(mean_model - 1) ]

    with H = -log(clip(S, s_floor, 1)).
    """
    composite = (chf_weight > 0 or cv_weight > 0 or mean_weight > 0)
    chf_emp = (-np.log(np.clip(S_emp, s_floor, 1.0)) if chf_weight > 0 else None)

    need_moments = (cv_weight > 0 or mean_weight > 0)
    # ONE solve serves both the curve and the moments. The moments need the fully absorbed tail, so
    # the horizon is raised to _MOMENT_TAU_MAX -- which costs nothing extra, because the solver
    # early-exits at Gtol as soon as the survival is absorbed. Running two solves (one per horizon)
    # doubled the per-evaluation cost for no accuracy gain.
    solve_tau_max = _MOMENT_TAU_MAX if need_moments else tau_max

    def resid(z):
        rho_eta = math.exp(z[0])
        rho_beta = math.exp(z[1])
        rho_eps = math.exp(z[2])
        kappa = (math.exp(z[3]) if use_full else KAPPA_FLOOR)
        G, m_mod, cv_mod, _se = fpt_full_survival(rho_eta, rho_beta, rho_eps, kappa,
                                                  tau_grid, N=N, dt=dt, tau_max=solve_tau_max)
        G = np.clip(G, 1e-9, 1.0)
        if not composite:
            return G - S_emp
        parts = [G - S_emp]
        if chf_weight > 0:
            parts.append(chf_weight * (-np.log(np.clip(G, s_floor, 1.0)) - chf_emp))
        if cv_weight > 0 and emp_cv is not None and np.isfinite(emp_cv):
            parts.append(np.array([cv_weight * (cv_mod - emp_cv)]))
        if mean_weight > 0:
            parts.append(np.array([mean_weight * (m_mod - 1.0)]))
        return np.concatenate(parts)
    return resid


def _fit_one_arm(tau_grid, S_emp, z0, use_full, N, dt, tau_max, max_nfev,
                 chf_weight=0.0, cv_weight=0.0, mean_weight=0.0, emp_cv=None,
                 s_floor=S_FLOOR, rho_ceil=RHO_CEIL):
    """Run least_squares from one start. Returns (z_opt, rms_composite, rms_survival, nfev).

    `rms_survival` is ALWAYS the survival-only RMS on `tau_grid`, so results stay comparable to
    runs made before the composite objective existed. `rms_composite` is what the optimizer saw.
    """
    ndim = 4 if use_full else 3
    z0 = list(z0[:ndim])
    lo = [math.log(1e-4), math.log(1e-4), math.log(1e-4)]
    hi = [math.log(rho_ceil)] * 3
    if use_full:
        lo.append(math.log(KAPPA_FLOOR))
        hi.append(math.log(KAPPA_CEIL))
    z0 = [min(max(v, l), u) for v, l, u in zip(z0, lo, hi)]
    resid = _resid_fn(tau_grid, S_emp, use_full, N, dt, tau_max,
                      chf_weight=chf_weight, cv_weight=cv_weight, mean_weight=mean_weight,
                      emp_cv=emp_cv, s_floor=s_floor)
    res = least_squares(resid, z0, method="trf", bounds=(lo, hi),
                        x_scale="jac", diff_step=3e-3,
                        xtol=1e-7, ftol=1e-7, gtol=1e-8, max_nfev=max_nfev)
    rms_comp = float(np.sqrt(np.mean(res.fun ** 2)))
    # survival-only RMS at the solution, for comparability with pre-composite runs
    s_resid = _resid_fn(tau_grid, S_emp, use_full, N, dt, tau_max)(res.x)
    rms_surv = float(np.sqrt(np.mean(s_resid ** 2)))
    return res.x, rms_comp, rms_surv, int(res.nfev)


def fp_curvefit_seed(death_times,
                     events=None,
                     xc: float = XC_NOMINAL,
                     use_full: bool = True,
                     ndims: int = 4,
                     hazard_plateau: float | None = None,
                     condition_age: float | None = None,
                     multistart: bool = True,
                     N: int = N_FIT,
                     dt: float = DT_FIT,
                     tau_max: float = TAU_MAX,
                     ngrid: int = NGRID,
                     max_nfev: int = 60,
                     starts=None,
                     chf_weight: float = 0.0,
                     cv_weight: float = 0.0,
                     mean_weight: float = 0.0,
                     s_floor: float = S_FLOOR,
                     rho_ceil: float = RHO_CEIL,
                     surface_start: bool = False) -> dict:
    """Deterministic near-MAP SR seed by fitting the full empirical survival curve.

    Parameters
    ----------
    death_times : array
        Per-individual lifetimes (any time unit; the fit is scale-free in tau=t/L).
    events : array or None
        1 = death observed, 0 = right-censored. None => all deaths (plain ECDF).
    xc : float
        Threshold Xc. NOT identifiable from the curve (cancels in the dimensionless round-trip);
        supply the config/nominal value. The physical eta,beta,epsilon,k scale with xc exactly as
        eta/Xc, beta/Xc, eps/Xc^2 are reported.
    use_full : bool
        True (default) -> full saturated FP, kappa free (restores strong-removal CV).
        False -> reduced 4th-param-free model (kappa fixed at the floor); faster, but gives CV ~ 0
        at strong removal and OVER-broadens sharp starts -- prefer full.
    ndims : int
        4 -> physical [eta, beta, epsilon, xc]; 5 -> also 'external_hazard' (Makeham).
    hazard_plateau : float or None
        For ndims=5: young-age age-independent hazard seed. None => DEFAULT_EXTERNAL_HAZARD.
    condition_age : float or None
        If set, drop individuals dying before this age and origin-shift the rest
        (t -> t - condition_age). Use to strip early-life/background mortality the 4-param SR model
        cannot represent (e.g. human infant mortality), so the fit sees the pure aging mode.
    multistart : bool
        If True (default) fit from BOTH a production start (omega>0) and a removal start (omega<0)
        and keep the lower-residual one -- this is what resolves the production/removal arm the
        (mean,CV) seed cannot. If False, only the removal start is used (the majority class).
    N, dt, tau_max, ngrid, max_nfev : solver / fit controls.
    starts : optional iterable of (rho_eta, rho_beta, rho_eps, kappa) custom starts.

    Returns
    -------
    dict with PHYSICAL seed keys eta, beta, epsilon, xc, k  (+ external_hazard if ndims==5), and
    diagnostics:
        rho_eta, rho_beta, rho_eps, kappa  -- fitted dimensionless params
        omega                              -- net-drift Peclet (0.5 rho_eta - rho_beta)/rho_eps
        arm                                -- 'production' (omega>0) or 'removal' (omega<0)
        L                                  -- data mean lifetime (the tau scale)
        fp_mean, fp_cv                     -- FP moments at the fit (fp_mean ~ 1 by construction)
        residual                           -- RMS of (G - S_emp) over the grid
        arm_resid                          -- {'production':rms, 'removal':rms} per start
        nfev                               -- function evaluations of the winning start
        wall_s                             -- wall-clock seconds for the whole seed-fit
        n, n_events                        -- sample size / observed deaths used
    """
    t0 = time.perf_counter()
    t = np.asarray(death_times, dtype=float)
    e = (np.ones(t.size, dtype=int) if events is None
         else np.asarray(events, dtype=int))

    if condition_age is not None:
        keep = t >= condition_age
        t = t[keep] - condition_age
        e = e[keep]
        if t.size == 0:
            raise ValueError("condition_age dropped all individuals")

    tk, Sk, L = kaplan_meier(t, e)
    if L <= 0:
        raise ValueError("non-positive mean lifetime from the survival curve")
    tau_grid, S_emp, _tau_hi = _empirical_on_taugrid(tk, Sk, L, ngrid=ngrid)

    composite = (chf_weight > 0 or cv_weight > 0 or mean_weight > 0)
    emp_cv = _empirical_cv(tk, Sk) if cv_weight > 0 else None

    # candidate starts (log-space)
    if starts is None:
        cand = [("removal", _START_REMOVAL)]
        if multistart:
            cand.insert(0, ("production", _START_PRODUCTION))
        if surface_start:
            ss = _surface_starts(S_emp, tau_grid)
            cand.extend(ss)
    else:
        cand = [(f"start{i}", s) for i, s in enumerate(starts)]
    if not use_full:
        # reduced model: kappa fixed; only 3 params, drop the kappa entry of each start
        cand = [(lbl, s[:3]) for lbl, s in cand]

    arm_resid = {}
    arm_resid_surv = {}
    best = None  # (rank_rms, z_opt, label, nfev, rms_surv)
    for lbl, s in cand:
        z0 = [math.log(max(v, 1e-4)) for v in s]
        z_opt, rms_c, rms_s, nfev = _fit_one_arm(
            tau_grid, S_emp, z0, use_full, N, dt, tau_max, max_nfev,
            chf_weight=chf_weight, cv_weight=cv_weight, mean_weight=mean_weight,
            emp_cv=emp_cv, s_floor=s_floor, rho_ceil=rho_ceil)
        arm_resid[lbl] = rms_c
        arm_resid_surv[lbl] = rms_s
        # Rank by the objective actually being optimized. Ranking a composite fit by survival-only
        # RMS (as avimayo's fit_mmchf_one.py does) reintroduces exactly the blindness the composite
        # rows were added to remove.
        rank = rms_c if composite else rms_s
        if best is None or rank < best[0]:
            best = (rank, z_opt, lbl, nfev, rms_s)

    _rank, z_opt, start_label, nfev, rms_surv = best
    rms = rms_surv if not composite else _rank
    rho_eta = math.exp(z_opt[0])
    rho_beta = math.exp(z_opt[1])
    rho_eps = math.exp(z_opt[2])
    kappa = (math.exp(z_opt[3]) if use_full else KAPPA_FLOOR)

    # polish moments on a finer grid (the fit grid is coarse for speed)
    _G, fp_mean, fp_cv, _se = fpt_full_survival(rho_eta, rho_beta, rho_eps, kappa,
                                                tau_grid, N=N_POLISH, dt=DT_POLISH,
                                                tau_max=tau_max)

    omega = (0.5 * rho_eta - rho_beta) / rho_eps
    arm = "production" if omega > 0 else "removal"

    eta, beta, epsilon, k = from_dimensionless(rho_beta, rho_eta, rho_eps, xc, L, kappa=kappa)

    seed = {
        "eta": eta, "beta": beta, "epsilon": epsilon, "xc": xc, "k": k,
        # diagnostics
        "rho_eta": rho_eta, "rho_beta": rho_beta, "rho_eps": rho_eps, "kappa": kappa,
        "omega": omega, "arm": arm, "start": start_label,
        "L": L, "fp_mean": fp_mean, "fp_cv": fp_cv,
        "residual": rms, "arm_resid": arm_resid, "nfev": nfev,
        # survival-only RMS is ALWAYS reported so composite runs stay comparable to older ones
        "residual_surv": rms_surv, "arm_resid_surv": arm_resid_surv,
        "composite": composite,
        "weights": dict(chf=chf_weight, cv=cv_weight, mean=mean_weight) if composite else None,
        "emp_cv": emp_cv,
        # never-absorbed gate: fp_mean at the horizon means the survival never decayed and the
        # "fit" is meaningless. avimayo's committed profile data contains such a point recorded as
        # legitimate (model_mean = 40.0 = tau_max, cv = 3e-6), so this is a real failure mode.
        "never_absorbed": bool(fp_mean >= 0.95 * tau_max),
        "bounds": {"rho_eta": (1e-4, rho_ceil), "rho_beta": (1e-4, rho_ceil),
                   "rho_eps": (1e-4, rho_ceil), "kappa": (KAPPA_FLOOR, KAPPA_CEIL)},
        "n": int(t.size), "n_events": int(np.sum(e == 1)),
        "use_full": use_full,
        "wall_s": time.perf_counter() - t0,
    }
    if ndims == 5:
        seed["external_hazard"] = (DEFAULT_EXTERNAL_HAZARD if hazard_plateau is None
                                   else float(hazard_plateau))
    return seed
