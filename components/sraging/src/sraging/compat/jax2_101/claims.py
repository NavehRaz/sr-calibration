def rbar(k: float) -> float:
    """MEAN removal factor over the damage range, 1 - k ln(1 + 1/k) (srbench.score.combos.removal_mean_factor's
    closed form; the kfix clone's `_rbar`)."""
    k = float(k)
    return 1.0 - k * math.log1p(1.0 / k)


