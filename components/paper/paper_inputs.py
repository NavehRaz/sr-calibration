"""List every input of the paper and where it goes in the release: writes release_inputs.json (read by the release's
assemble.py, which copies the `copy` and `git` files into the data deposit under paper_inputs/).

Inputs are (1) every claim's source in claims.toml and (2) every file the scripts in tables/ and figures/ read, as
recorded in script_inputs.txt by running them with SR_RECORD_INPUTS=script_inputs.txt (see README.md).

    python -B paper_inputs.py     # on the author's machine only; reads, never writes sources
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import paper_paths as PP  # noqa: E402

# sraging paths released as code at the tag (VERSIONS.toml, component "sraging"); files excluded there are listed too
SRAGING_CODE = ("src/", "pyproject.toml", "uv.lock", "README.md", "docs/algorithms/", "examples/", "divergences/",
                "tests/")


def dest_of(name: str):
    """(kind, relative place) in the release, or ("not_public", reason)."""
    n = PP.norm(name)
    best = None
    for pre, dest, why in PP.RELEASE_MAP:
        if n.startswith(pre) and (best is None or len(pre) > len(best[0])):
            best = (pre, dest, why)
    if best is None:
        return "not_public", "not part of this release"
    pre, dest, why = best
    if dest is None:
        return "not_public", why
    kind, rest = dest.split(":", 1)
    return kind, rest + n[len(pre):]


def git_blob(rev: str, path: str) -> str:
    return subprocess.run(["git", "-C", PP.local(PP.SRAGING), "rev-parse", f"{rev}:{path}"],
                          capture_output=True, text=True, check=True).stdout.strip()


def main() -> int:
    claims = tomllib.load(open(os.path.join(HERE, "claims.toml"), "rb"))["claim"]
    names: dict[str, set[str]] = {}
    gits: dict[tuple[str, str], set[str]] = {}
    for c in claims:
        loc = c["locator"]
        if loc["kind"] == "git":
            gits.setdefault((loc["rev"], loc["path"]), set()).add(c["id"])
            continue
        names.setdefault(PP.norm(c["source"]), set()).add(c["id"])
        for sub in ("num", "den"):
            if sub in loc and loc[sub].get("source"):
                names.setdefault(PP.norm(loc[sub]["source"]), set()).add(c["id"])
    rec = os.path.join(HERE, "script_inputs.txt")
    for line in open(rec).read().split():
        if line.startswith("git:"):
            rev, path = line[4:].split("/", 1)
            gits.setdefault((rev, path), set()).add("script")
        else:
            names.setdefault(line, set()).add("script")

    out = {"note": "generated by paper_inputs.py; do not edit", "sraging_tag": PP.SRAGING_TAG,
           "copy": [], "records": [], "git": [], "in_release": [], "not_public": [], "problems": []}
    for n in sorted(names):
        kind, where = dest_of(n)
        users = sorted(names[n])
        if kind == "not_public":
            out["not_public"].append({"input": n, "reason": where, "used_by": users})
        elif "/__records__/" in n:
            tester, run = n.split("/__records__/")
            out["records"].append({"tester": tester, "run": run.strip("/"), "to": where})
        elif kind == "data" and where.startswith("paper_inputs/"):
            if not os.path.isfile(PP.local(n)):
                out["problems"].append(f"missing: {n}")
            out["copy"].append({"from": n, "to": where, "used_by": users})
        else:
            if n.startswith(PP.SRAGING + "/"):     # a working-tree file of sraging, released at the tag
                rel = n[len(PP.SRAGING) + 1:]
                try:
                    same = git_blob(PP.SRAGING_TAG, rel) == git_blob("HEAD", rel) and not subprocess.run(
                        ["git", "-C", PP.local(PP.SRAGING), "diff", "--quiet", "HEAD", "--", rel]).returncode
                except subprocess.CalledProcessError:
                    same = False
                if not same:
                    out["problems"].append(f"sraging working tree differs from {PP.SRAGING_TAG}: {rel}")
            out["in_release"].append({"input": n, "at": f"{kind}:{where}"})
    for (rev, path), users in sorted(gits.items()):
        released = rev == PP.SRAGING_TAG and path.startswith(SRAGING_CODE)
        evidence = rev == PP.SRAGING_TAG and path.startswith("specs/")
        if released or evidence:
            out["in_release"].append({"input": f"git:{rev}/{path}", "at": "code:components/sraging/" + path
                                      if released else "data:sraging_evidence/" + path})
        else:
            out["git"].append({"rev": rev, "path": path, "to": f"paper_inputs/git/{rev}/{path}",
                               "used_by": sorted(users)})
    with open(os.path.join(HERE, "release_inputs.json"), "w") as f:
        json.dump(out, f, indent=1)
    print(f"release_inputs.json: copy {len(out['copy'])}, records {len(out['records'])}, git {len(out['git'])}, "
          f"in release {len(out['in_release'])}, not public {len(out['not_public'])}, problems {len(out['problems'])}")
    for p in out["problems"]:
        print("  PROBLEM", p)
    return 1 if out["problems"] else 0


if __name__ == "__main__":
    sys.exit(main())
